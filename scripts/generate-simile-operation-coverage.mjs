import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const openapiDir = resolve(scriptDir, "..");
const specificationPath = resolve(openapiDir, "commerce.yml");
const outputPath = resolve(openapiDir, "SIMILE_OPERATION_COVERAGE.md");
const document = YAML.parse(readFileSync(specificationPath, "utf8"));
const methods = new Set(["delete", "get", "patch", "post", "put"]);
const scenarios = new Map([
  ["sendChime", "chime_cooldown_active"],
  ["createOrder", "order_payment_method_invalid"],
  ["createRefund", "refund_currency_mismatch"],
  ["schedulePayout", "payout_restricted"],
  ["tokenizePaymentMethod", "payment_method_tokenized<br>payment_method_invalid_body"],
  ["createProduct", "product_created<br>product_gallery_too_large"],
  ["createPurchaseIntent", "purchase_intent_created<br>purchase_intent_invalid_quantity_range"],
]);
const rows = [];

for (const [path, item] of Object.entries(document.paths ?? {})) {
  for (const [method, operation] of Object.entries(item ?? {})) {
    if (!methods.has(method)) continue;
    const requestMedia = operation.requestBody?.content ?? {};
    const openapiRequestExamples = Object.values(requestMedia).some(hasExample);
    const successes = [];
    const errors = [];
    const named = [];
    const synthesized = [];
    const clauses = new Set();

    for (const media of Object.values(requestMedia)) collectConstraints(media.schema, clauses);
    for (const [status, response] of Object.entries(operation.responses ?? {})) {
      const statusList = /^2\d\d$/.test(status) || /^3\d\d$/.test(status) ? successes : errors;
      statusList.push(status);
      for (const media of Object.values(response.content ?? {})) {
	collectConstraints(media.schema, clauses);
	const names = Object.keys(media.examples ?? {});
	if (names.length > 0) {
	  named.push(...names.map((name) => `${status}:${name}`));
	} else if (media.example !== undefined) {
	  named.push(`${status}:example`);
	} else if (media.schema) {
	  synthesized.push(status);
	}
      }
    }

    rows.push({
      operation: `\`${operation.operationId}\`<br>${method.toUpperCase()} \`${path}\``,
      request: openapiRequestExamples ? "OpenAPI + validated clients" : "Validated Insomnia/Postman client",
      successes: unique(successes).join(", ") || "—",
      errors: unique(errors).join(", ") || "—",
      constraints: [...clauses].sort().join(", ") || "ordinary OpenAPI only",
      named: named.join("<br>") || "none",
      hcl: scenarios.get(operation.operationId) ?? "none",
      synthesized: unique(synthesized).join(", ") || "none",
    });
  }
}

rows.sort((left, right) => left.operation.localeCompare(right.operation));

const lines = [
  "# Inttegro Simile operation coverage",
  "",
  "> Generated by `node scripts/generate-simile-operation-coverage.mjs`. Do not edit by hand.",
  "",
  `The OpenAPI contract exposes ${rows.length} operations. Every operation has a validated Insomnia request and generated Postman equivalent. ` +
    "Named outcomes are exact OpenAPI examples; all other listed response statuses remain schema-synthesized. HCL adds only opaque scenario selectors for exact HTTP-emulator outcomes.",
  "",
  "| Operation | Request example | Success outcomes | Error outcomes | Soundness clauses reachable from request/response | Named OpenAPI outcome | HCL scenario | Remaining schema-synthesized statuses |",
  "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ...rows.map((row) =>
    `| ${row.operation} | ${row.request} | ${row.successes} | ${row.errors} | ${row.constraints} | ${row.named} | ${row.hcl} | ${row.synthesized} |`,
  ),
  "",
  "HCL declares only the ten scenario selectors shown above. The public implementation evidence did not justify protocol overrides, abstract dependencies, or declared asynchronous work beyond the OpenAPI contract.",
  "",
];

const rendered = lines.join("\n");
if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== rendered) {
    throw new Error("SIMILE_OPERATION_COVERAGE.md is stale; run npm run simile:coverage");
  }
  console.log(`Simile operation coverage is current for ${rows.length} operations`);
} else {
  writeFileSync(outputPath, rendered);
  console.log(`Wrote ${rows.length} operations to ${outputPath}`);
}

function hasExample(media) {
  return media?.example !== undefined || Object.keys(media?.examples ?? {}).length > 0;
}

function collectConstraints(input, result, seen = new Set()) {
  if (!input || typeof input !== "object") return;
  if (input.$ref) {
    if (seen.has(input.$ref)) return;
    seen.add(input.$ref);
    const target = resolveRef(input.$ref);
    collectConstraints(target, result, seen);
    seen.delete(input.$ref);
    return;
  }
  for (const constraint of input["x-simile-constraints"] ?? []) {
    const clause = Object.keys(constraint)[0];
    if (clause) result.add(clause);
  }
  for (const property of Object.values(input.properties ?? {})) collectConstraints(property, result, seen);
  collectConstraints(input.items, result, seen);
  collectConstraints(input.additionalProperties, result, seen);
  for (const keyword of ["allOf", "anyOf", "oneOf"]) {
    for (const branch of input[keyword] ?? []) collectConstraints(branch, result, seen);
  }
  collectConstraints(input.not, result, seen);
}

function resolveRef(reference) {
  if (!reference.startsWith("#/")) return undefined;
  return reference
    .slice(2)
    .split("/")
    .map((part) => part.replaceAll("~1", "/").replaceAll("~0", "~"))
    .reduce((value, part) => value?.[part], document);
}

function unique(values) {
  return [...new Set(values)];
}
